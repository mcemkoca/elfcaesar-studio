def draw(canvas, name: str, cx: float, cy: float, size: float, color: str,
         width: float = 1.6, tag: str = "icon") -> None:
    spec = ICONS.get(name)
    if not spec:
        return
    x0, y0 = cx - size / 2, cy - size / 2

    def pts(seq):
        return [x0 + v * size if i % 2 == 0 else y0 + v * size for i, v in enumerate(seq)]

    for kind, coords in spec:
        c = pts(coords)
        if kind == L:
            canvas.create_line(*c, fill=color, width=width, capstyle="round",
                               joinstyle="round", tags=tag)
        elif kind == O:
            canvas.create_oval(*c, outline=color, width=width, tags=tag)
        elif kind == R:
            canvas.create_rectangle(*c, outline=color, width=width, tags=tag)
        elif kind == P:
            canvas.create_polygon(*c, outline=color, fill="", width=width,
                                  joinstyle="round", tags=tag)


def icon_label(parent, name: str, color: str, size: int = 16, bg: str | None = None, pad: int = 2):
    """Küçük, bağımsız ikon tuvali döndürür."""
    import tkinter as tk
    box = size + pad * 2
    c = tk.Canvas(parent, width=box, height=box, bg=bg or parent.cget("bg"),
                  highlightthickness=0, bd=0)
    draw(c, name, box / 2, box / 2, size, color, width=max(1.2, size / 10))
    return c
